-- 001: 実際に使うセンサーに合わせてカラムを入れ替える
-- ============================================================
-- 【この SQL を実行する前に、IoTチームの確認を取ること】
--
-- 経緯:
--   発注するセンサーが確定した結果、当初の想定と 2 か所ずれがあった。
--
--   ・照度センサーが構成に入らなかった → lux は測れない
--   ・そのかわり GPS（NEO-6M）が速度を返すので、追加部品なしで速度が取れる
--   → lux を speed_kmh に入れ替える
--
--   ・塩分は、静電容量式センサーでは測れない（電極が絶縁されているため）。
--     電極 2 本 + ADS1015 の自作EC計で測る方針にしたので、
--     salinity_pct / tds_ppm はそのまま残す。
--   ・静電容量式センサー(SEN0308)は「こってり度」に転用する。
--     水は誘電率が高く(約80)、油は低い(約2〜3)ため、
--     脂の多いスープほど値が変わることを利用する。
--   → richness_mv を追加する
-- ============================================================

-- ------------------------------------------------------------
-- 走行計測点: 照度 → 速度
-- ------------------------------------------------------------
alter table ride_points add column speed_kmh real;   -- GPS から得た速度（km/h）
alter table ride_points drop column lux;

-- ------------------------------------------------------------
-- ラーメン計測: こってり度を追加（塩分・TDS はそのまま残す）
-- ------------------------------------------------------------
-- 「こってり度」は解釈が入る言葉なので、DB にはセンサーの生の出力電圧を保存し、
-- どう見せるかは画面側で決める。あとから基準を変えても記録は残る。
alter table ramen_measurements add column richness_mv real;  -- SEN0308 の出力電圧（mV）
